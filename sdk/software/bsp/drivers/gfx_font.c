static const gfx_font_desc_t g_font_desc_table[] = {
    {4u, 6u},
    {5u, 7u},
    {6u, 8u}
};

static gfx_font_id_t gfx_font_normalize(gfx_font_id_t font_id)
{
    if ((font_id != GFX_FONT_4X6) &&
        (font_id != GFX_FONT_5X7) &&
        (font_id != GFX_FONT_6X8)) {
        return GFX_FONT_4X6;
    }
    return font_id;
}

static U8 gfx_font_pixel_5x7(U8 ch, U8 x, U8 y)
{
    U8 glyph_idx;
    U8 glyph_col;

    if (x >= 5u || y >= 7u) {
        return 0u;
    }

    glyph_idx = (U8)(ch - 0x20u);
    glyph_col = g_font_5x7[glyph_idx][x];
    return (U8)((glyph_col >> y) & 0x1u);
}

gfx_font_id_t gfx_font_from_string(const char *name)
{
    if (name == 0) {
        return GFX_FONT_4X6;
    }

    if ((name[0] == '4') && ((name[1] == 'x') || (name[1] == 'X')) && (name[2] == '6') && (name[3] == '\0')) {
        return GFX_FONT_4X6;
    }
    if ((name[0] == '5') && ((name[1] == 'x') || (name[1] == 'X')) && (name[2] == '7') && (name[3] == '\0')) {
        return GFX_FONT_5X7;
    }
    if ((name[0] == '6') && ((name[1] == 'x') || (name[1] == 'X')) && (name[2] == '8') && (name[3] == '\0')) {
        return GFX_FONT_6X8;
    }

    return GFX_FONT_4X6;
}

const gfx_font_desc_t *gfx_font_desc(gfx_font_id_t font_id)
{
    gfx_font_id_t id = gfx_font_normalize(font_id);
    return &g_font_desc_table[(int)id];
}

U8 gfx_font_pixel(gfx_font_id_t font_id, char ch, U8 x, U8 y)
{
    U8 uch;
    gfx_font_id_t id;

    uch = (U8)ch;
    if ((uch < 0x20u) || (uch > 0x7eu)) {
        return 0u;
    }

    id = gfx_font_normalize(font_id);

    if (id == GFX_FONT_5X7) {
        return gfx_font_pixel_5x7(uch, x, y);
    }

    if (id == GFX_FONT_6X8) {
        if ((x >= 6u) || (y >= 8u)) {
            return 0u;
        }
        if ((x == 5u) || (y == 7u)) {
            return 0u;
        }
        return gfx_font_pixel_5x7(uch, x, y);
    }

    if ((x >= 4u) || (y >= 6u)) {
        return 0u;
    }

    return gfx_font_pixel_5x7(
        uch,
        (U8)((x * 5u) / 4u),
        (U8)((y * 7u) / 6u)
    );
}

